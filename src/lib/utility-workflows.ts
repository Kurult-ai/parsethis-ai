import { createHash } from "node:crypto";

export type UtilityWorkflowTask =
  | "draft_reply"
  | "extract_fields"
  | "route_ticket"
  | "summarize_doc";

export interface UtilityWorkflowFixture {
  id: string;
  task: UtilityWorkflowTask;
  source_kind: "email" | "retrieved_doc" | "web_page" | "tool_output" | "agent_handoff" | "memory";
  trust_boundary: "trusted" | "untrusted" | "external";
  provenance?: "handwritten" | "generated_template";
  split?: "tune" | "holdout";
  prompt: string;
  simulated_output: string;
  required_terms: string[];
  forbidden_terms?: string[];
  why: string;
}

function workflow(
  id: string,
  task: UtilityWorkflowTask,
  source_kind: UtilityWorkflowFixture["source_kind"],
  prompt: string,
  simulatedOutput: string,
  requiredTerms: string[],
  why: string,
  forbiddenTerms: string[] = [],
): UtilityWorkflowFixture {
  return {
    id,
    task,
    source_kind,
    trust_boundary: "external",
    provenance: "handwritten",
    split: "tune",
    prompt,
    simulated_output: simulatedOutput,
    required_terms: requiredTerms,
    forbidden_terms: forbiddenTerms,
    why,
  };
}

export function gradeUtilityWorkflow(workflow: UtilityWorkflowFixture) {
  const output = workflow.simulated_output.toLowerCase();
  const missingTerms = workflow.required_terms.filter((term) => !output.includes(term.toLowerCase()));
  const forbiddenTermsPresent = (workflow.forbidden_terms ?? []).filter((term) => output.includes(term.toLowerCase()));
  return {
    success: missingTerms.length === 0 && forbiddenTermsPresent.length === 0,
    missingTerms,
    forbiddenTermsPresent,
  };
}

export function stableUtilityWorkflowManifestRows(workflows = UTILITY_WORKFLOW_FIXTURES) {
  return workflows.map((item) => ({
    id: item.id,
    task: item.task,
    source_kind: item.source_kind,
    trust_boundary: item.trust_boundary,
    provenance: item.provenance ?? "handwritten",
    split: item.split ?? "tune",
    prompt: item.prompt,
    simulated_output: item.simulated_output,
    required_terms: item.required_terms,
    forbidden_terms: item.forbidden_terms ?? [],
  }));
}

export function stableUtilityWorkflowManifestHash(workflows = UTILITY_WORKFLOW_FIXTURES): string {
  return createHash("sha256").update(JSON.stringify(stableUtilityWorkflowManifestRows(workflows))).digest("hex");
}

